function normalizeAscii(value: string): string {
  return value
    .normalize('NFKD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/[ıİ]/g, 'i')
    .replace(/[øØ]/g, 'o')
    .replace(/[æÆ]/g, 'ae')
    .replace(/[ß]/g, 'ss');
}

function sanitizePrefix(value: string): string {
  return normalizeAscii(String(value || ''))
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '')
    .replace(/^\d+/, '')
    .slice(0, 16);
}

function extractRawNameLines(): string[] {
  return RAW_EMAIL_PREFIX_NAMES.split('\n')
    .map((line) => line.trim())
    .filter(Boolean)
    .filter((line) => !/^(pakistan|turkey|hollywood|south indian|japan)$/i.test(line));
}

export function fallbackPopularPersonPrefixes(minCount = 2000): string[] {
  const rows = extractRawNameLines();
  const firstNames: string[] = [];
  const lastNames: string[] = [];
  const out: string[] = [];
  const seen = new Set<string>();

  const push = (raw: string) => {
    const s = sanitizePrefix(raw);
    if (s.length < 3 || seen.has(s)) return;
    seen.add(s);
    out.push(s);
  };

  for (const row of rows) {
    push(row);
    const parts = normalizeAscii(row)
      .split(/\s+/)
      .map((part) => part.replace(/[^a-z0-9'-]/gi, '').trim())
      .filter((part) => part.length >= 2);
    if (!parts.length) continue;
    firstNames.push(parts[0]);
    lastNames.push(parts[parts.length - 1]);
    push(parts[0]);
    if (parts.length > 1) push(parts[parts.length - 1]);
  }

  const uniqueFirst = [...new Set(firstNames.map((name) => sanitizePrefix(name)).filter((name) => name.length >= 3))];
  const uniqueLast = [...new Set(lastNames.map((name) => sanitizePrefix(name)).filter((name) => name.length >= 3))];

  for (const first of uniqueFirst) {
    for (const last of uniqueLast) {
      push(`${first}${last}`);
      if (out.length >= minCount) return out;
    }
  }

  return out;
}

export function pickRandomPrefixes(source: string[], count: number): string[] {
  const arr = [...source];
  for (let i = arr.length - 1; i > 0; i -= 1) {
    const j = Math.floor(Math.random() * (i + 1));
    [arr[i], arr[j]] = [arr[j], arr[i]];
  }
  return arr.slice(0, count);
}
